const body = document.body;
const documentRoot = document.documentElement;
const topbar = document.querySelector(".topbar");
const brandLink = document.getElementById("brandLink");
const siteNav = document.getElementById("siteNav");
const menuToggle = document.getElementById("menuToggle");
const headerMenu = document.getElementById("headerMenu");
const langToggle = document.getElementById("langToggle");
const langValue = document.getElementById("langValue");
const themeToggle = document.getElementById("themeToggle");
const metaDescription = document.getElementById("metaDescription");
const themeColorMeta = document.getElementById("themeColorMeta");
const i18nNodes = document.querySelectorAll("[data-i18n]");
const revealItems = document.querySelectorAll(".reveal");
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const mobileViewport = window.matchMedia("(max-width: 920px)");
const THEME_KEY = "site-theme-v2";
const CONTACT_SCHEMES = {
  email: "mailto:"
};
const CONTACT_VALUES = {
  email: [100, 97, 108, 108, 103, 97, 116, 111, 118, 64, 103, 109, 97, 105, 108, 46, 99, 111, 109]
};

function readStorage(key) {
  try {
    return localStorage.getItem(key);
  } catch (error) {
    return null;
  }
}

function writeStorage(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch (error) {
    // Storage can be unavailable in restricted or private contexts.
  }
}

let currentLang = readStorage("site-lang") || document.documentElement.lang || "ru";
let currentTheme = readStorage(THEME_KEY) || body.dataset.theme || "dark";
let topbarScrollTicking = false;

function getDictionary() {
  return translations[currentLang] || translations.ru;
}

function decodeContact(kind) {
  const codes = CONTACT_VALUES[kind];
  if (!codes) {
    return "";
  }

  return String.fromCharCode(...codes);
}

function getProtectedContactHref(kind) {
  const scheme = CONTACT_SCHEMES[kind];
  const value = decodeContact(kind);
  if (!scheme || !value) {
    return "";
  }

  return `${scheme}${value}`;
}

function getContactDisplayValue(kind) {
  const value = decodeContact(kind);
  if (!value) {
    return "";
  }

  return value;
}

function bindProtectedContacts() {
  document.querySelectorAll("[data-protected-contact]").forEach((node) => {
    const kind = node.dataset.protectedContact;
    const href = getProtectedContactHref(kind);
    if (!href) {
      return;
    }

    node.setAttribute("href", href);
  });

  document.querySelectorAll("[data-contact-display]").forEach((node) => {
    const kind = node.dataset.contactDisplay;
    const value = getContactDisplayValue(kind);
    if (!value) {
      return;
    }

    node.textContent = value;
  });
}

function syncMenuAccessibility() {
  if (!headerMenu) {
    return;
  }

  const isMenuHidden = mobileViewport.matches && !topbar?.classList.contains("menu-open");
  headerMenu.setAttribute("aria-hidden", isMenuHidden ? "true" : "false");
}

function closeMenu() {
  if (!topbar || !menuToggle) {
    return;
  }

  topbar.classList.remove("menu-open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", getDictionary()["controls.menuOpen"] || "Open menu");
  syncMenuAccessibility();
}

function openMenu() {
  if (!topbar || !menuToggle) {
    return;
  }

  topbar.classList.add("menu-open");
  menuToggle.setAttribute("aria-expanded", "true");
  menuToggle.setAttribute("aria-label", getDictionary()["controls.menuClose"] || "Close menu");
  syncMenuAccessibility();
}

function toggleMenu() {
  if (!topbar) {
    return;
  }

  const isOpen = topbar.classList.contains("menu-open");
  if (isOpen) {
    closeMenu();
  } else {
    openMenu();
  }
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations.ru;

  i18nNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (!dict[key]) {
      return;
    }

    node.textContent = dict[key];
  });

  currentLang = lang;
  documentRoot.lang = lang;
  document.title = dict["meta.title"] || document.title;

  if (metaDescription && dict["meta.description"]) {
    metaDescription.setAttribute("content", dict["meta.description"]);
  }

  if (langValue) {
    langValue.textContent = lang.toUpperCase();
  }

  if (brandLink) {
    brandLink.setAttribute("aria-label", dict["brand.ariaLabel"] || "Home");
  }

  if (siteNav) {
    siteNav.setAttribute("aria-label", dict["nav.ariaLabel"] || "Primary navigation");
  }

  if (langToggle) {
    langToggle.setAttribute("aria-label", dict["controls.langAria"] || "Language");
  }

  if (themeToggle) {
    themeToggle.setAttribute("aria-label", dict["controls.themeAria"] || "Theme");
  }

  if (menuToggle) {
    const isOpen = topbar && topbar.classList.contains("menu-open");
    menuToggle.setAttribute("aria-label", isOpen ? dict["controls.menuClose"] : dict["controls.menuOpen"]);
  }

  writeStorage("site-lang", lang);
}

function applyTheme(theme) {
  currentTheme = theme === "dark" ? "dark" : "light";
  body.dataset.theme = currentTheme;
  writeStorage(THEME_KEY, currentTheme);

  if (themeColorMeta) {
    themeColorMeta.setAttribute("content", currentTheme === "dark" ? "#101514" : "#f4f2ed");
  }
}

function syncTopbarState() {
  if (!topbar) {
    return;
  }

  topbar.classList.toggle("is-scrolled", window.scrollY > 18);
}

function requestTopbarStateSync() {
  if (topbarScrollTicking) {
    return;
  }

  topbarScrollTicking = true;
  window.requestAnimationFrame(() => {
    syncTopbarState();
    topbarScrollTicking = false;
  });
}

function bindMediaQueryChange(query, callback) {
  if (!query) {
    return;
  }

  if (typeof query.addEventListener === "function") {
    query.addEventListener("change", callback);
    return;
  }

  if (typeof query.addListener === "function") {
    query.addListener(callback);
  }
}

if (langToggle) {
  langToggle.addEventListener("click", () => {
    langToggle.classList.add("switching");
    applyLanguage(currentLang === "ru" ? "en" : "ru");
    window.setTimeout(() => {
      langToggle.classList.remove("switching");
    }, 360);
  });
}

if (themeToggle) {
  themeToggle.addEventListener("click", () => {
    applyTheme(currentTheme === "dark" ? "light" : "dark");
  });
}

if (menuToggle && headerMenu) {
  menuToggle.addEventListener("click", toggleMenu);

  headerMenu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      closeMenu();
    });
  });
}

if (!reduceMotion && "IntersectionObserver" in window) {
  const revealOptions = mobileViewport.matches
    ? { threshold: 0.08, rootMargin: "0px 0px -6% 0px" }
    : { threshold: 0.16, rootMargin: "0px 0px -10% 0px" };
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("in-view");
        observer.unobserve(entry.target);
      }
    });
  }, revealOptions);

  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("in-view"));
}

document.addEventListener("click", (event) => {
  if (!topbar || !mobileViewport.matches) {
    return;
  }

  if (!topbar.contains(event.target)) {
    closeMenu();
  }
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeMenu();
  }
});

window.addEventListener("scroll", requestTopbarStateSync, { passive: true });
bindMediaQueryChange(mobileViewport, () => {
  closeMenu();
  syncMenuAccessibility();
});

applyLanguage(currentLang === "en" ? "en" : "ru");
applyTheme(currentTheme);
bindProtectedContacts();
syncTopbarState();
closeMenu();
